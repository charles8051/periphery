using System.Globalization;
using System.Text;

namespace Periphery.DebugProbe.AlgorithmGen;

/// <summary>Everything one generated record is made from.</summary>
internal sealed record RecordInput(
    string FieldName,
    FlmAlgorithm Flm,
    PdscAlgorithm Pdsc,
    string Pack,
    string Version,
    string FlmPath,
    string Sha256,
    string Notice);

/// <summary>
/// Writes one flash algorithm record as C#. Deterministic: the same input always gives the same
/// text, which is how the generator gate in ADR-0094's Verification is checked.
/// </summary>
internal static class RecordWriter
{
    public static string Write(RecordInput input)
    {
        var flm = input.Flm;
        if (flm.FlashStart != input.Pdsc.Start || flm.FlashSize != input.Pdsc.Size)
            throw new InvalidDataException(
                $"The FLM covers 0x{flm.FlashStart:X8}+0x{flm.FlashSize:X} but the pack lists " +
                $"0x{input.Pdsc.Start:X8}+0x{input.Pdsc.Size:X}.");

        var sb = new StringBuilder();
        sb.Append("// <auto-generated>\n");
        sb.Append("// Generated by Periphery.DebugProbe.AlgorithmGen (ADR-0094 D9). Do not edit; regenerate.\n");
        sb.Append(Invariant($"// Source: {input.Pack} {input.Version}, {input.FlmPath}\n"));
        sb.Append(Invariant($"// SHA-256 of the FLM: {input.Sha256}\n"));
        sb.Append("// </auto-generated>\n");
        sb.Append("//\n");
        foreach (var line in input.Notice.Replace("\r\n", "\n").TrimEnd('\n').Split('\n'))
            sb.Append(line.Length == 0 ? "//\n" : $"// {line}\n");
        sb.Append('\n');
        sb.Append("using Periphery.DebugProbe.Flash;\n\n");
        sb.Append("namespace Periphery.DebugProbe.Targets;\n\n");
        sb.Append("internal static partial class FlashAlgorithms\n{\n");
        sb.Append(Invariant($"    /// <summary>{flm.Name}.</summary>\n"));
        sb.Append(Invariant($"    public static readonly FlashAlgorithm {input.FieldName} = new(\n"));
        sb.Append(Invariant($"        Name: \"{flm.Name}\",\n"));
        sb.Append("        Code: new byte[]\n        {\n");
        for (int i = 0; i < flm.Code.Length; i += 16)
        {
            var row = flm.Code.Skip(i).Take(16).Select(b => Invariant($"0x{b:X2}"));
            sb.Append("            ").Append(string.Join(", ", row)).Append(",\n");
        }
        sb.Append("        },\n");
        sb.Append(Invariant($"        InitOffset: 0x{flm.InitOffset:X},\n"));
        sb.Append(Invariant($"        UnInitOffset: 0x{flm.UnInitOffset:X},\n"));
        sb.Append(Invariant($"        EraseSectorOffset: 0x{flm.EraseSectorOffset:X},\n"));
        sb.Append(Invariant($"        ProgramPageOffset: 0x{flm.ProgramPageOffset:X},\n"));
        sb.Append(Invariant($"        DataSectionOffset: 0x{flm.DataSectionOffset:X},\n"));
        sb.Append(Invariant($"        FlashStart: 0x{flm.FlashStart:X8},\n"));
        sb.Append(Invariant($"        FlashSize: 0x{flm.FlashSize:X},\n"));
        sb.Append(Invariant($"        PageSize: 0x{flm.PageSize:X},\n"));
        sb.Append(Invariant($"        ErasedValue: 0x{flm.ErasedValue:X2},\n"));
        sb.Append(Invariant($"        ProgramPageTimeout: TimeSpan.FromMilliseconds({flm.ProgramPageTimeoutMs}),\n"));
        sb.Append(Invariant($"        EraseSectorTimeout: TimeSpan.FromMilliseconds({flm.EraseSectorTimeoutMs}),\n"));
        sb.Append("        Sectors: [")
          .Append(string.Join(", ", flm.Sectors.Select(s => Invariant($"new(0x{s.Size:X}, 0x{s.Offset:X})"))))
          .Append("],\n");
        sb.Append(Invariant($"        RamStart: 0x{input.Pdsc.RamStart:X8},\n"));
        sb.Append(Invariant($"        RamSize: 0x{input.Pdsc.RamSize:X},\n"));
        sb.Append(Invariant($"        Provenance: new(\"{input.Pack}\", \"{input.Version}\", \"{input.FlmPath}\", \"{input.Sha256}\"));\n"));
        sb.Append("}\n");
        return sb.ToString();
    }

    private static string Invariant(FormattableString text) => text.ToString(CultureInfo.InvariantCulture);
}
